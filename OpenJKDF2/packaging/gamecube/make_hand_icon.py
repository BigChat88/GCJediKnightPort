#!/usr/bin/env python3
# Makes the "use" hand shown over things the B button can activate (the way the
# console Jedi Knight II games show it) from hand_source.png, a pointing hand in
# outline: the inside is filled teal with a blue side and a yellow-green rim, the
# lines are drawn dark. Writes src/Platform/GameCube/gcHandIcon.h (GX RGB5A3,
# already in 4x4 tiles) and optionally a preview PNG.
#
#   python make_hand_icon.py [preview.png]

import os
import sys
from PIL import Image, ImageDraw

SIZE = 64        # texture size
PAD = 2          # transparent border in the texture (pixels)

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'hand_source.png')
OUT_H = os.path.join(HERE, '..', '..', 'src', 'Platform', 'GameCube', 'gcHandIcon.h')

# Left to right across the hand: blue side, teal body, light cyan, yellow-green rim.
STOPS = [(0.00, (40, 95, 225)), (0.35, (55, 170, 230)), (0.60, (70, 220, 225)),
         (0.82, (120, 235, 215)), (1.00, (200, 235, 70))]
LINE = (10, 25, 45)


def grad(t):
    for (ta, ca), (tb, cb) in zip(STOPS, STOPS[1:]):
        if t <= tb:
            k = (t - ta) / (tb - ta) if tb > ta else 0
            return tuple(int(a + (b - a) * k) for a, b in zip(ca, cb))
    return STOPS[-1][1]


def main():
    src = Image.open(SRC).convert('RGBA')
    # A transparent margin first: the drawing touches the image's right and
    # bottom edges, which would close off the corner between them and the hand
    # from the flood below (it got filled as if inside).
    m = 8
    padded = Image.new('RGBA', (src.size[0] + 2 * m, src.size[1] + 2 * m), (0, 0, 0, 0))
    padded.paste(src, (m, m))
    src = padded
    w, h = src.size
    # The lines are the opaque pixels; everything else is transparent. Flood the
    # outside from a corner: what the flood doesn't reach is the inside.
    lines = src.getchannel('A').point(lambda a: 255 if a > 96 else 0)
    flood = lines.convert('L').copy()
    ImageDraw.floodfill(flood, (0, 0), 128)
    fp, lp = flood.load(), lines.load()

    bbox = lines.getbbox()
    x0, x1 = bbox[0], bbox[2]
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    px = img.load()
    for y in range(h):
        light = 1.0 + 0.12 * (1.0 - y / h)   # a little lighter towards the top
        for x in range(w):
            if lp[x, y]:
                px[x, y] = LINE + (235,)
            elif fp[x, y] == 0:              # inside
                c = grad((x - x0) / max(1, x1 - x0))
                px[x, y] = tuple(min(255, int(v * light)) for v in c) + (255,)

    # Fit the hand into the texture, keeping its proportions, centred.
    img = img.crop(bbox)
    bw, bh = img.size
    scale = (SIZE - 2 * PAD) / max(bw, bh)
    tw, th = max(1, round(bw * scale)), max(1, round(bh * scale))
    small = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0))
    small.paste(img.resize((tw, th), Image.LANCZOS), ((SIZE - tw) // 2, (SIZE - th) // 2))
    if len(sys.argv) > 1:
        small.resize((SIZE * 4, SIZE * 4), Image.NEAREST).save(sys.argv[1])

    def rgb5a3(r, g, b, a):
        if a >= 0xE0:
            return 0x8000 | ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3)
        return ((a >> 5) << 12) | ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4)

    sp = small.load()
    words = []
    for ty in range(0, SIZE, 4):
        for tx in range(0, SIZE, 4):
            for y in range(4):
                for x in range(4):
                    words.append(rgb5a3(*sp[tx + x, ty + y]))
    with open(OUT_H, 'w', newline='\n') as f:
        f.write('// Generated by packaging/gamecube/make_hand_icon.py -- do not edit.\n')
        f.write('// The "use" hand (GX_TF_RGB5A3, %dx%d, 4x4 tiles).\n' % (SIZE, SIZE))
        f.write('#define GC_HAND_ICON_SIZE %d\n' % SIZE)
        f.write('static const uint16_t gcHandIcon_rgb5a3[%d] __attribute__((aligned(32))) = {\n' % len(words))
        for i in range(0, len(words), 12):
            f.write('    ' + ', '.join('0x%04X' % w for w in words[i:i + 12]) + ',\n')
        f.write('};\n')
    print('wrote', os.path.normpath(OUT_H))


if __name__ == '__main__':
    main()
