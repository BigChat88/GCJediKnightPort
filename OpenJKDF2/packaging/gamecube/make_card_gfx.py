#!/usr/bin/env python3
"""Generate src/Platform/GameCube/gcCardGfx.h: the memory card banner (96x32) and
icon (32x32) shown by the GameCube's memory card screen and by Swiss, as tiled
RGB5A3 texels -- one set per game (Jedi Knight, Mysteries of the Sith).

    python make_card_gfx.py [--banner card_banner.png] [--icon card_icon.png] [-o header]

Re-run after changing either image (any size; they are scaled).
"""

import argparse
import os
import struct

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))


def rgb5a3(r, g, b, a):
    if a >= 0xE0:
        return 0x8000 | ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3)
    return ((a >> 5) << 12) | ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4)


def tiled_rgb5a3(path, w, h):
    im = Image.open(path).convert("RGBA")
    if im.size != (w, h):
        im = im.resize((w, h), Image.LANCZOS)
    px = im.load()
    out = bytearray()
    for ty in range(0, h, 4):          # 4x4 texel tiles
        for tx in range(0, w, 4):
            for y in range(ty, ty + 4):
                for x in range(tx, tx + 4):
                    out += struct.pack(">H", rgb5a3(*px[x, y]))
    return bytes(out)


def c_array(name, data):
    lines = [f"static const unsigned char {name}[{len(data)}] __attribute__((aligned(32))) = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--banner", default=os.path.join(HERE, "card_banner.png"))
    ap.add_argument("--icon", default=os.path.join(HERE, "card_icon.png"))
    ap.add_argument("--mots-banner", default=os.path.join(HERE, "card_banner_mots.png"),
                    help="Mysteries of the Sith card banner")
    ap.add_argument("--mots-icon", default=os.path.join(HERE, "card_icon_mots.png"),
                    help="Mysteries of the Sith card icon")
    ap.add_argument("-o", "--out", default=os.path.join(HERE, "..", "..", "src", "Platform", "GameCube", "gcCardGfx.h"))
    args = ap.parse_args()

    banner = tiled_rgb5a3(args.banner, 96, 32)
    icon = tiled_rgb5a3(args.icon, 32, 32)
    banner_mots = tiled_rgb5a3(args.mots_banner, 96, 32)
    icon_mots = tiled_rgb5a3(args.mots_icon, 32, 32)
    with open(args.out, "w", newline="\n") as f:
        f.write("// Generated by packaging/gamecube/make_card_gfx.py -- do not edit.\n")
        f.write("// Memory card banner (96x32) and icon (32x32), tiled RGB5A3, for Jedi Knight\n")
        f.write("// and for Mysteries of the Sith (*Mots).\n")
        f.write("#ifndef _PLATFORM_GAMECUBE_GCCARDGFX_H\n#define _PLATFORM_GAMECUBE_GCCARDGFX_H\n\n")
        f.write(c_array("gcCardGfx_banner", banner) + "\n\n")
        f.write(c_array("gcCardGfx_icon", icon) + "\n\n")
        f.write(c_array("gcCardGfx_bannerMots", banner_mots) + "\n\n")
        f.write(c_array("gcCardGfx_iconMots", icon_mots) + "\n\n")
        f.write("#endif\n")
    print(f"{args.out}: banner {len(banner)} bytes, icon {len(icon)} bytes")


if __name__ == "__main__":
    main()
